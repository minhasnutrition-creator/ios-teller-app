import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow

enum class LanguageType(val displayName: String) {
    ACCOUNTING("Accounting (Professional)"),
    SIMPLE("Simple (Human Readable)")
}

enum class UiLanguage(val displayName: String) {
    ENGLISH("English"),
    HINDI("Hindi (हिन्दी)"),
    PUNJABI("Punjabi (ਪੰਜਾਬੀ)")
}

object TerminologyManager {
    private const val PREFS_NAME = "TerminologyPrefs"
    private const val LANGUAGE_KEY = "language_type"
    private const val UI_LANGUAGE_KEY = "ui_language"
    
    private val _currentLanguage = MutableStateFlow(LanguageType.SIMPLE)
    val currentLanguage: StateFlow<LanguageType> = _currentLanguage.asStateFlow()

    private val _currentUiLanguage = MutableStateFlow(UiLanguage.ENGLISH)
    val currentUiLanguage: StateFlow<UiLanguage> = _currentUiLanguage.asStateFlow()

    private var isInitialized = false

    fun initialize(context: Context) {
        if (isInitialized) return
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val langName = prefs.getString(LANGUAGE_KEY, LanguageType.SIMPLE.name)
        _currentLanguage.value = try {
            LanguageType.valueOf(langName ?: LanguageType.SIMPLE.name)
        } catch (e: Exception) {
            LanguageType.SIMPLE
        }
        val uiLangName = prefs.getString(UI_LANGUAGE_KEY, UiLanguage.ENGLISH.name)
        _currentUiLanguage.value = try {
            UiLanguage.valueOf(uiLangName ?: UiLanguage.ENGLISH.name)
        } catch (e: Exception) {
            UiLanguage.ENGLISH
        }
        isInitialized = true
    }

    fun setLanguage(context: Context, type: LanguageType) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit().putString(LANGUAGE_KEY, type.name).apply()
        _currentLanguage.value = type
    }

    fun setUiLanguage(context: Context, type: UiLanguage) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit().putString(UI_LANGUAGE_KEY, type.name).apply()
        _currentUiLanguage.value = type
    }

    fun getTerm(key: String, default: String = key): String {
        val englishTerm = if (_currentLanguage.value == LanguageType.SIMPLE) {
             simpleTerms[key]?.first ?: default
        } else {
             default
        }

        return when (_currentUiLanguage.value) {
            UiLanguage.HINDI -> hindiTerms[englishTerm] ?: hindiTermsExtra[englishTerm]
                ?: hindiTerms[key] ?: hindiTermsExtra[key] ?: englishTerm
            UiLanguage.PUNJABI -> punjabiTerms[englishTerm] ?: punjabiTerms[key] ?: englishTerm
            UiLanguage.ENGLISH -> englishTerm
        }
    }
    
    fun getDescription(key: String): String? {
         return when (_currentUiLanguage.value) {
             UiLanguage.ENGLISH -> {
                 if (_currentLanguage.value == LanguageType.SIMPLE) {
                     simpleTerms[key]?.second
                 } else {
                     null
                 }
             }
             else -> null
         }
    }

    /**
     * Reverse lookup: Finds the Technical (Accounting) term for a given Simple term.
     * Useful when the user/AI uses simple language but DB needs technical.
     */
    fun getTechnicalTerm(simpleTerm: String): String {
        val entry = simpleTerms.entries.find { it.value.first.equals(simpleTerm, ignoreCase = true) }
        return entry?.key ?: simpleTerm
    }
    
    // Helper to check if a term is a known simple group name
    fun isSimpleGroup(term: String): Boolean {
        return simpleTerms.values.any { it.first.equals(term, ignoreCase = true) }
    }

