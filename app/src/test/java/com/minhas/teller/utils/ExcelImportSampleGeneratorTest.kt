package com.minhas.teller.utils

import com.minhas.teller.TellerApp
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test

class ExcelImportSampleGeneratorTest {

    @Before
    fun setUp() {
        TellerApp.configureGlobalProperties()
    }

    @Test
    fun testBuildAllSampleWorkbooks() {
        for (template in ExcelImportSampleGenerator.VoucherTemplate.values()) {
            val bytes = ExcelImportSampleGenerator.buildWorkbookBytes(template)
            assertNotNull("Generated bytes should not be null for $template", bytes)
            assertTrue("Generated bytes should not be empty for $template", bytes.isNotEmpty())
            assertTrue("Generated bytes should be a valid ZIP/XLSX file (PK header)", bytes[0] == 0x50.toByte() && bytes[1] == 0x4B.toByte())
        }
    }
}
